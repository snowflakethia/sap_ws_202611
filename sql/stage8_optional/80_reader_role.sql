USE ROLE ACCOUNTADMIN;

CREATE ROLE IF NOT EXISTS DEMO_READER_ROLE
    COMMENT = 'Read-only access to the GNN Supply Chain Risk demo';
GRANT ROLE DEMO_READER_ROLE TO ROLE SYSADMIN;
EXECUTE IMMEDIATE $$
BEGIN
  EXECUTE IMMEDIATE 'GRANT ROLE DEMO_READER_ROLE TO USER "' || REPLACE(CURRENT_USER(), '"', '""') || '"';
  RETURN 'DEMO_READER_ROLE granted to ' || CURRENT_USER();
END;
$$;

-- Compute
GRANT USAGE ON WAREHOUSE DEMO_19865_WH TO ROLE DEMO_READER_ROLE;
GRANT USAGE ON COMPUTE POOL DEMO_19865_POOL TO ROLE DEMO_READER_ROLE;
