USE ROLE DEMO_19865_ROLE;
USE WAREHOUSE DEMO_19865_WH;
USE SCHEMA DEMO_19865_DB.GNN_SUPPLY_CHAIN_RISK;

CREATE TABLE IF NOT EXISTS TRADE_DATA_EXTERNAL (
    BOL_ID              VARCHAR(20)  NOT NULL,
    SHIPPER_NAME        VARCHAR(255) NOT NULL,
    SHIPPER_COUNTRY     VARCHAR(3),
    CONSIGNEE_NAME      VARCHAR(255) NOT NULL,
    CONSIGNEE_COUNTRY   VARCHAR(3),
    HS_CODE             VARCHAR(10)  NOT NULL,
    HS_DESCRIPTION      VARCHAR(255),
    SHIP_DATE           DATE NOT NULL,
    WEIGHT_KG           FLOAT,
    VALUE_USD           FLOAT,
    PORT_OF_ORIGIN      VARCHAR(100),
    PORT_OF_DESTINATION VARCHAR(100),
    CREATED_AT          TIMESTAMP_NTZ(9) DEFAULT CURRENT_TIMESTAMP(),
    PRIMARY KEY (BOL_ID)
) COMMENT = 'External trade data - bills of lading for Tier 2+ inference';

CREATE TABLE IF NOT EXISTS REGIONS_EXTERNAL (
    REGION_CODE           VARCHAR(3)   NOT NULL,
    REGION_NAME           VARCHAR(100) NOT NULL,
    BASE_RISK_SCORE       FLOAT DEFAULT 0,
    GEOPOLITICAL_RISK     FLOAT DEFAULT 0,
    NATURAL_DISASTER_RISK FLOAT DEFAULT 0,
    INFRASTRUCTURE_SCORE  FLOAT DEFAULT 0.5,
    UPDATED_AT            TIMESTAMP_NTZ(9) DEFAULT CURRENT_TIMESTAMP(),
    PRIMARY KEY (REGION_CODE)
) COMMENT = 'Geographic region risk factors';

CREATE TABLE IF NOT EXISTS CUSTOMER_CONTRACTS (
    CONTRACT_ID      VARCHAR,
    CONTRACT_TITLE   VARCHAR,
    SUPPLIER_NAME    VARCHAR,
    BUYER_NAME       VARCHAR,
    SUPPLIER_COUNTRY VARCHAR,
    BUYER_COUNTRY    VARCHAR,
    MATERIAL_TYPE    VARCHAR,
    CONTRACT_DATE    DATE,
    ANNUAL_VALUE_USD NUMBER(18,2),
    CONTRACT_TEXT    VARCHAR,
    CREATED_AT       DATE
) COMMENT = 'Customer supply chain contracts for Cortex Search demo'
  CHANGE_TRACKING = TRUE;  -- required by the Cortex Search service (incremental refresh)

CREATE TABLE IF NOT EXISTS RISK_SCORES_PREDICTIONS (
    SCORE_ID             NUMBER(38,0) NOT NULL AUTOINCREMENT START 1 INCREMENT 1 NOORDER,
    NODE_ID              VARCHAR(50) NOT NULL,
    NODE_TYPE            VARCHAR(20) NOT NULL,
    RISK_SCORE           FLOAT NOT NULL,
    RISK_CATEGORY        VARCHAR(20),
    CONFIDENCE           FLOAT,
    EMBEDDING            ARRAY,
    CONTRIBUTING_FACTORS VARIANT,
    MODEL_VERSION        VARCHAR(50),
    CALCULATED_AT        TIMESTAMP_NTZ(9) DEFAULT CURRENT_TIMESTAMP(),
    PRIMARY KEY (SCORE_ID)
) COMMENT = 'GNN-computed risk scores for all supply chain nodes';

CREATE TABLE IF NOT EXISTS SUPPLIER_LINKS_PREDICTIONS (
    LINK_ID           NUMBER(10,0) NOT NULL,
    SOURCE_NODE_ID    VARCHAR,
    SOURCE_NODE_TYPE  VARCHAR,
    TARGET_NODE_ID    VARCHAR,
    TARGET_NODE_TYPE  VARCHAR,
    LINK_TYPE         VARCHAR,
    PROBABILITY       NUMBER(11,10),
    EVIDENCE_STRENGTH VARCHAR,
    SUPPORTING_DATA   VARCHAR,
    MODEL_VERSION     VARCHAR,
    PREDICTED_AT      VARCHAR,
    PRIMARY KEY (LINK_ID)
) COMMENT = 'GNN-predicted hidden supplier relationships';

CREATE TABLE IF NOT EXISTS BOTTLENECKS_PREDICTIONS (
    BOTTLENECK_ID     NUMBER(38,0) NOT NULL AUTOINCREMENT START 1 INCREMENT 1 NOORDER,
    NODE_ID           VARCHAR(50) NOT NULL,
    NODE_TYPE         VARCHAR(20) NOT NULL,
    DEPENDENT_COUNT   NUMBER(38,0) NOT NULL,
    DEPENDENT_NODES   ARRAY,
    IMPACT_SCORE      FLOAT NOT NULL,
    DESCRIPTION       VARCHAR(500),
    MITIGATION_STATUS VARCHAR(20) DEFAULT 'UNMITIGATED',
    IDENTIFIED_AT     TIMESTAMP_NTZ(9) DEFAULT CURRENT_TIMESTAMP(),
    PRIMARY KEY (BOTTLENECK_ID)
) COMMENT = 'Identified single points of failure in supply chain';
