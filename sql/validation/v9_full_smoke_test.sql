USE ROLE ACCOUNTADMIN;
USE WAREHOUSE DEMO_19865_WH;

SHOW AGENTS LIKE 'GNN_SUPPLY_RISK_AGENT' IN SCHEMA DEMO_19865_DB.GNN_SUPPLY_CHAIN_RISK;
SET V_AGENT = (SELECT COUNT(*) FROM TABLE(RESULT_SCAN(LAST_QUERY_ID())));

SHOW CORTEX SEARCH SERVICES LIKE 'CONTRACT_SEARCH_SERVICE' IN SCHEMA DEMO_19865_DB.GNN_SUPPLY_CHAIN_RISK;
SET V_SEARCH = (SELECT MAX("indexing_state" || '/' || "serving_state") FROM TABLE(RESULT_SCAN(LAST_QUERY_ID())));

SHOW SEMANTIC VIEWS LIKE 'SUPPLY_CHAIN_RISK_SEMANTIC_VIEW' IN SCHEMA DEMO_19865_DB.GNN_SUPPLY_CHAIN_RISK;
SET V_SV = (SELECT COUNT(*) FROM TABLE(RESULT_SCAN(LAST_QUERY_ID())));

LS 'snow://workspace/DEMO_SHARED_WORKSPACES.DEMO_19865_WORKSPACE.DEMO_19865/versions/head/';
SET V_FILES = (SELECT COUNT(*) FROM TABLE(RESULT_SCAN(LAST_QUERY_ID())));

WITH r AS (
    SELECT
        (SELECT COUNT(*) FROM S4_ZVENDORINFO_DP_DELTA_SHARING_V1."s4_zvendorinfo_dp_srv:v1"."s4custom_vendors")
      + (SELECT COUNT(*) FROM S4_ZMATERIALS_DP_DELTA_SHARING_V1."s4_zmaterials_dp_srv:v1"."s4custom_materials")
      + (SELECT COUNT(*) FROM S4_ZPURCHASEORDERS_DP_DELTA_SHARING_V1."s4_zpurchaseorders_dp_srv:v1"."s4custom_purchase_orders")
      + (SELECT COUNT(*) FROM S4_ZBILLOFMATERIALS_DP_DELTA_SHARING_V1."s4_zbillofmaterials_dp_srv:v1"."s4custom_billofmaterials") AS SAP_ROWS,
        (SELECT COUNT(*) FROM DEMO_19865_DB.GNN_SUPPLY_CHAIN_RISK.BOTTLENECKS_PREDICTIONS)
      + (SELECT COUNT(*) FROM DEMO_19865_DB.GNN_SUPPLY_CHAIN_RISK.CUSTOMER_CONTRACTS)
      + (SELECT COUNT(*) FROM DEMO_19865_DB.GNN_SUPPLY_CHAIN_RISK.REGIONS_EXTERNAL)
      + (SELECT COUNT(*) FROM DEMO_19865_DB.GNN_SUPPLY_CHAIN_RISK.RISK_SCORES_PREDICTIONS)
      + (SELECT COUNT(*) FROM DEMO_19865_DB.GNN_SUPPLY_CHAIN_RISK.SUPPLIER_LINKS_PREDICTIONS)
      + (SELECT COUNT(*) FROM DEMO_19865_DB.GNN_SUPPLY_CHAIN_RISK.TRADE_DATA_EXTERNAL) AS DEMO_ROWS,
        (SELECT COUNT(*) FROM DEMO_19865_DB.GNN_SUPPLY_CHAIN_RISK.VW_RISK_SUMMARY) AS SUMMARY_ROWS
)
SELECT 'S9 SAP snapshot rows' AS CHECK_NAME, '219' AS EXPECTED, SAP_ROWS::VARCHAR AS ACTUAL, IFF(SAP_ROWS = 219, 'PASS', 'FAIL') AS RESULT FROM r
UNION ALL SELECT 'S9 demo table rows', '648', DEMO_ROWS::VARCHAR, IFF(DEMO_ROWS = 648, 'PASS', 'FAIL') FROM r
UNION ALL SELECT 'S9 VW_RISK_SUMMARY rows', '2', SUMMARY_ROWS::VARCHAR, IFF(SUMMARY_ROWS = 2, 'PASS', 'FAIL') FROM r
UNION ALL SELECT 'S9 search service state', 'ACTIVE/ACTIVE', COALESCE($V_SEARCH, 'missing'), IFF($V_SEARCH = 'ACTIVE/ACTIVE', 'PASS', 'FAIL')
UNION ALL SELECT 'S9 semantic view', '1', $V_SV::VARCHAR, IFF($V_SV = 1, 'PASS', 'FAIL')
UNION ALL SELECT 'S9 agent', '1', $V_AGENT::VARCHAR, IFF($V_AGENT = 1, 'PASS', 'FAIL')
UNION ALL SELECT 'S9 workspace files', '7', $V_FILES::VARCHAR, IFF($V_FILES = 7, 'PASS', 'FAIL');
