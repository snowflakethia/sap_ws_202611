USE ROLE DEMO_19865_ROLE;
USE WAREHOUSE DEMO_19865_WH;
USE SCHEMA DEMO_19865_DB.GNN_SUPPLY_CHAIN_RISK;

WITH t AS (
              SELECT 'BOTTLENECKS_PREDICTIONS' AS T, 10 AS EXPECTED, (SELECT COUNT(*) FROM BOTTLENECKS_PREDICTIONS) AS ACTUAL
    UNION ALL SELECT 'CUSTOMER_CONTRACTS', 12, (SELECT COUNT(*) FROM CUSTOMER_CONTRACTS)
    UNION ALL SELECT 'REGIONS_EXTERNAL', 9, (SELECT COUNT(*) FROM REGIONS_EXTERNAL)
    UNION ALL SELECT 'RISK_SCORES_PREDICTIONS', 86, (SELECT COUNT(*) FROM RISK_SCORES_PREDICTIONS)
    UNION ALL SELECT 'SUPPLIER_LINKS_PREDICTIONS', 381, (SELECT COUNT(*) FROM SUPPLIER_LINKS_PREDICTIONS)
    UNION ALL SELECT 'TRADE_DATA_EXTERNAL', 150, (SELECT COUNT(*) FROM TRADE_DATA_EXTERNAL)
),
s AS (SELECT * FROM VW_RISK_SUMMARY),
v AS (
              SELECT 'VW_SUPPLIER_RISK' AS V, 50 AS EXPECTED, (SELECT COUNT(*) FROM VW_SUPPLIER_RISK) AS ACTUAL
    UNION ALL SELECT 'VW_MATERIAL_RISK', 26, (SELECT COUNT(*) FROM VW_MATERIAL_RISK)
    UNION ALL SELECT 'VW_HIDDEN_DEPENDENCIES', 26, (SELECT COUNT(*) FROM VW_HIDDEN_DEPENDENCIES)
)
SELECT 'S4-A rows ' || T AS CHECK_NAME, EXPECTED::VARCHAR AS EXPECTED, ACTUAL::VARCHAR AS ACTUAL,
       IFF(ACTUAL = EXPECTED, 'PASS', 'FAIL') AS RESULT FROM t
UNION ALL
SELECT 'S4-A rows TOTAL', '648', (SELECT SUM(ACTUAL) FROM t)::VARCHAR, IFF((SELECT SUM(ACTUAL) FROM t) = 648, 'PASS', 'FAIL')
UNION ALL
SELECT 'S4-B VW_RISK_SUMMARY ' || CATEGORY || ' total/critical/high/avg',
       DECODE(CATEGORY, 'SUPPLIERS', '50/2/4/0.4060', 'PARTS', '26/0/0/0.4768'),
       TOTAL_COUNT || '/' || CRITICAL_COUNT || '/' || HIGH_COUNT || '/' || TO_CHAR(ROUND(AVG_RISK_SCORE, 4), 'FM0.0000'),
       IFF(TOTAL_COUNT || '/' || CRITICAL_COUNT || '/' || HIGH_COUNT || '/' || TO_CHAR(ROUND(AVG_RISK_SCORE, 4), 'FM0.0000')
           = DECODE(CATEGORY, 'SUPPLIERS', '50/2/4/0.4060', 'PARTS', '26/0/0/0.4768'), 'PASS', 'FAIL') FROM s
UNION ALL
SELECT 'S4-B VW_RISK_SUMMARY row count', '2', (SELECT COUNT(*) FROM s)::VARCHAR, IFF((SELECT COUNT(*) FROM s) = 2, 'PASS', 'FAIL')
UNION ALL
SELECT 'S4-C rows ' || V, EXPECTED::VARCHAR, ACTUAL::VARCHAR, IFF(ACTUAL = EXPECTED, 'PASS', 'FAIL') FROM v
UNION ALL
SELECT 'S4-C JSON columns restored (EMBEDDING is ARRAY)', 'ARRAY',
       (SELECT MAX(TYPEOF(EMBEDDING)) FROM RISK_SCORES_PREDICTIONS),
       IFF((SELECT MAX(TYPEOF(EMBEDDING)) FROM RISK_SCORES_PREDICTIONS) = 'ARRAY', 'PASS', 'FAIL');
